    def _init_models_and_scores(self):
        # 1. Train and Score Supplier Risk Model
        self.sup_features_df = RiskFeatureExtractor.extract_supplier_features(
            self.suppliers_df, self.receipts_df, self.inspections_df, self.pos_df, self.materials_df
        )
        self.sup_model = ExplainableSupplierRiskModel()
        self.supplier_predictions = self.sup_model.predict_and_explain(self.sup_features_df)
        self.supplier_score_lookup = {p["supplier_id"]: p for p in self.supplier_predictions}

        # 2. Train and Score Material Stockout Risk Model
        self.mat_features_df = RiskFeatureExtractor.extract_material_features(
            self.materials_df, self.movements_df, self.pos_df, self.bom_df
        )
        self.stockout_model = ExplainableStockoutRiskModel()
        self.material_predictions = self.stockout_model.predict_and_explain(self.mat_features_df)
        self.material_score_lookup = {p["material_id"]: p for p in self.material_predictions}

