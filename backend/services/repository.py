    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(SupplyGuardRepository, cls).__new__(cls)
            cls._instance.initialized = False
        return cls._instance

    def __init__(self):
        if self.initialized:
            return
        self.data_dir = os.getenv("DATA_DIR", "data")
        self._load_datasets()
        self._init_models_and_scores()
        self._init_operational_state()
