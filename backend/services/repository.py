    # Query APIs
    def get_kpis(self) -> Dict[str, Any]:
        total_pos = len(self.pos_df)
        delivered_pos = len(self.receipts_df)
        otd_rate = round(float((self.receipts_df["delivery_variance_days"] <= 0).mean() * 100.0), 1)

        overdue_df = self.pos_df[self.pos_df["status"] == "OVERDUE"]
        spend_at_risk = round(float(overdue_df["total_amount"].sum()), 2)

        stockouts = sum(1 for p in self.material_predictions if p["days_of_inventory"] <= 0 or p["risk_tier"] == "CRITICAL")
        
        # Total inventory valuation
        inv_val = round(float((self.mat_features_df["current_stock"] * self.mat_features_df["standard_cost"]).sum()), 2)
        avg_doi = round(float(self.mat_features_df["days_of_inventory"].median()), 1)

        high_risk_sups = sum(1 for p in self.supplier_predictions if p["risk_tier"] in ("CRITICAL", "HIGH"))
        active_alerts = sum(1 for a in self.alerts.values() if a["status"] == "ACTIVE")
        open_actions = sum(1 for c in self.corrective_actions.values() if c["status"] in ("OPEN", "IN_PROGRESS"))

        return {
            "on_time_delivery_rate": otd_rate,
            "total_spend_at_risk_usd": spend_at_risk,
            "active_stockouts_count": stockouts,
            "total_inventory_valuation_usd": inv_val,
            "average_days_of_inventory": avg_doi,
            "high_risk_suppliers_count": high_risk_sups,
            "active_alerts_count": active_alerts,
            "open_corrective_actions_count": open_actions
        }

    def get_suppliers(
        self, 
        tier: Optional[str] = None, 
        category: Optional[str] = None, 
        risk_tier: Optional[str] = None,
        search: Optional[str] = None
    ) -> List[Dict[str, Any]]:
        results = []
        for p in self.supplier_predictions:
            s_info = self.suppliers_df[self.suppliers_df["supplier_id"] == p["supplier_id"]].iloc[0]
            if tier and s_info["tier"] != tier:
                continue
            if category and s_info["category"] != category:
                continue
            if risk_tier and p["risk_tier"] != risk_tier:
                continue
            if search:
                s_lower = search.lower()
                if s_lower not in s_info["name"].lower() and s_lower not in s_info["code"].lower() and s_lower not in s_info["supplier_id"].lower():
                    continue

            # Overdue spend
            sup_pos = self.pos_df[self.pos_df["supplier_id"] == p["supplier_id"]]
            overdue_spend = sup_pos[sup_pos["status"] == "OVERDUE"]["total_amount"].sum()
            total_spend = sup_pos["total_amount"].sum()

            results.append({
                "supplier_id": p["supplier_id"],
                "code": s_info["code"],
                "name": s_info["name"],
                "category": s_info["category"],
                "country": s_info["country"],
                "city": s_info["city"],
                "tier": s_info["tier"],
                "reliability_rating": s_info["reliability_rating"],
                "financial_health_score": s_info["financial_health_score"],
                "otd_percentage": p["otd_rate_90d"],
                "avg_lead_time_variance_days": p["lead_time_variance_avg"],
                "lead_time_variance_std": round(float(p.get("lead_time_variance_std", 2.1)), 1),
                "overall_defect_ppm": p["defect_ppm_90d"],
                "total_spend": round(float(total_spend), 2),
                "overdue_spend": round(float(overdue_spend), 2),
                "risk_score": p["risk_score"],
                "risk_tier": p["risk_tier"],
                "top_contributing_factors": p["top_contributing_factors"],
                "explanation_text": RiskNarrativeExplainer.generate_supplier_explanation(p)
            })

        results.sort(key=lambda x: x["risk_score"], reverse=True)
        return results

    def get_supplier_by_id(self, supplier_id: str) -> Optional[Dict[str, Any]]:
        sups = self.get_suppliers(search=supplier_id)
        for s in sups:
            if s["supplier_id"] == supplier_id:
                return s
        return None

    def get_materials(
        self,
        category: Optional[str] = None,
        risk_tier: Optional[str] = None,
        is_critical: Optional[bool] = None,
        search: Optional[str] = None,
        limit: int = 200
    ) -> List[Dict[str, Any]]:
        results = []
        for p in self.material_predictions:
            m_info = self.materials_df[self.materials_df["material_id"] == p["material_id"]].iloc[0]
            if category and m_info["category"] != category:
                continue
            if risk_tier and p["risk_tier"] != risk_tier:
                continue
            if is_critical is not None and m_info["is_critical"] != is_critical:
                continue
            if search:
                s_lower = search.lower()
                if s_lower not in m_info["name"].lower() and s_lower not in m_info["sku"].lower():
                    continue

            current_stock = p["current_stock"]
            safety = m_info["safety_stock_level"]
            reorder = m_info["reorder_point"]

            if current_stock <= 0:
                health = "STOCKOUT"
            elif current_stock < safety:
                health = "SAFETY_STOCK_BREACH"
            elif current_stock < reorder:
                health = "REORDER_TRIGGER"
            else:
                health = "HEALTHY"

            results.append({
                "material_id": p["material_id"],
                "sku": m_info["sku"],
                "name": m_info["name"],
                "category": m_info["category"],
                "unit_of_measure": m_info["unit_of_measure"],
                "standard_cost": m_info["standard_cost"],
                "safety_stock_level": safety,
                "reorder_point": reorder,
                "current_stock": current_stock,
                "days_of_inventory": p["days_of_inventory"],
                "stock_health_status": health,
                "is_critical": bool(m_info["is_critical"]),
                "stockout_risk_score": p["stockout_risk_score"],
                "risk_tier": p["risk_tier"],
                "explanation_text": RiskNarrativeExplainer.generate_stockout_explanation(p)
            })

        results.sort(key=lambda x: x["stockout_risk_score"], reverse=True)
        return results[:limit]

    def get_purchase_orders(
        self,
        status: Optional[str] = None,
        supplier_id: Optional[str] = None,
        search: Optional[str] = None,
        limit: int = 150
    ) -> List[Dict[str, Any]]:
        df = self.pos_df.copy()
        if status:
            df = df[df["status"] == status]
        if supplier_id:
            df = df[df["supplier_id"] == supplier_id]

        sup_map = self.suppliers_df.set_index("supplier_id")["name"].to_dict()
        results = []
        now = datetime(2026, 4, 15)

        for _, row in df.iterrows():
            if search:
                s_lower = search.lower()
                if s_lower not in row["po_number"].lower() and s_lower not in row["po_id"].lower():
                    continue

            p_date = datetime.strptime(row["promised_delivery_date"], "%Y-%m-%d")
            overdue_days = max(0, (now - p_date).days) if row["status"] == "OVERDUE" else 0

            results.append({
                "po_id": row["po_id"],
                "po_number": row["po_number"],
                "supplier_id": row["supplier_id"],
                "supplier_name": sup_map.get(row["supplier_id"], ""),
                "order_date": row["order_date"],
                "promised_delivery_date": row["promised_delivery_date"],
                "status": row["status"],
                "total_amount": float(row["total_amount"]),
                "currency": row.get("currency", "USD"),
                "days_overdue": overdue_days
            })

        results.sort(key=lambda x: (x["status"] == "OVERDUE", x["days_overdue"]), reverse=True)
        return results[:limit]

    def get_alerts(self, severity: Optional[str] = None, alert_type: Optional[str] = None) -> List[Dict[str, Any]]:
        items = list(self.alerts.values())
        if severity:
            items = [a for a in items if a["severity"] == severity]
        if alert_type:
            items = [a for a in items if a["alert_type"] == alert_type]
        items.sort(key=lambda x: x["created_at"], reverse=True)
        return items

    def update_alert_status(self, alert_id: str, status: str) -> Optional[Dict[str, Any]]:
        if alert_id in self.alerts:
            self.alerts[alert_id]["status"] = status
            if status == "RESOLVED":
                self.alerts[alert_id]["resolved_at"] = datetime.utcnow()
            return self.alerts[alert_id]
        return None

    def get_corrective_actions(self, status: Optional[str] = None) -> List[Dict[str, Any]]:
        items = list(self.corrective_actions.values())
        if status:
            items = [c for c in items if c["status"] == status]
        items.sort(key=lambda x: x["updated_at"], reverse=True)
        return items

    def create_corrective_action(self, payload: Dict[str, Any]) -> Dict[str, Any]:
        action_id = f"CA-2026-{len(self.corrective_actions) + 1:04d}"
        now = datetime.utcnow()
        new_act = {
            "action_id": action_id,
            "alert_id": payload.get("alert_id"),
            "title": payload["title"],
            "description": payload["description"],
            "assigned_to": payload["assigned_to"],
            "priority": payload.get("priority", "HIGH"),
            "status": "OPEN",
            "root_cause": payload.get("root_cause"),
            "mitigation_plan": payload.get("mitigation_plan"),
            "resolution_notes": None,
            "target_completion_date": payload.get("target_completion_date"),
            "created_at": now,
            "updated_at": now,
            "resolved_at": None
        }
        self.corrective_actions[action_id] = new_act
        return new_act

    def update_corrective_action(self, action_id: str, payload: Dict[str, Any]) -> Optional[Dict[str, Any]]:
        if action_id not in self.corrective_actions:
            return None
        act = self.corrective_actions[action_id]
        for k, v in payload.items():
            if v is not None:
                act[k] = v
        act["updated_at"] = datetime.utcnow()
        if act.get("status") == "RESOLVED" and not act.get("resolved_at"):
            act["resolved_at"] = datetime.utcnow()
        return act

    def get_etl_audit_logs(self) -> List[Dict[str, Any]]:
        return sorted(self.etl_audit_logs, key=lambda x: x["start_time"], reverse=True)

    def get_etl_rejected_records(self) -> List[Dict[str, Any]]:
        return sorted(self.etl_rejected_records, key=lambda x: x["rejected_at"], reverse=True)

    def get_data_quality_results(self) -> List[Dict[str, Any]]:
        return sorted(self.data_quality_results, key=lambda x: x["executed_at"], reverse=True)
